"""phase_2_export_model.py - Phase 2, step 4: train the frozen classifier on ALL 15 subjects and export it.
Training rows: binary task, normalised (calibration mean subtracted), calibration windows excluded.
Gate threshold: GATE_ACT_PCT of acc_activity over seated calm windows (GATE_REF_LABELS) of all subjects.
Outputs: firmware/sshrc/src/model_params.h         (int8 weights, int32 bias, scales, impute/scaler vectors,
                                                    gate threshold, feature order)
         logs/SSHRC_L2_model_export.json          (same parameters + training counts, for the documents)
         logs/SSHRC_L2_golden_classifier.csv      (N_GOLDEN windows: normalised features -> expected int32
                                                    accumulator, class, logit; for the C unit test, phase 3)
Usage (from the repository root):  python python/phase_2_export_model.py                 (all 15 subjects: final model)
                                   python python/phase_2_export_model.py --exclude S2 S6 (phase-4 model: S2, S6 unseen)
Run record: logs/console/, logs/config_snapshots/, logs/runs.csv (see runlog.py).
"""
import argparse
import json

import numpy as np
import pandas as pd

import config as C
from calib import feature_cols, task_table
from loso import make_model
from quant import float_logit, int8_logit, quantize
from runlog import RunLog

TAG = f"w{C.WINDOW_S}_h{C.HOP_S}"


# Formats one C array line of model_params.h.
def arr(name, ctype, v, fmt):
    body = ", ".join(fmt(x) for x in v)
    return f"static const {ctype} {name}[N_FEAT] = {{ {body} }};"


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument("--exclude", nargs="*", default=[], choices=C.SUBJECTS,
                    help="subjects left out of training (out-of-sample demo)")
    excl = ap.parse_args().exclude
    # 1. Training data: normalised features of all subjects (minus any --exclude subject).
    df, all_cols = task_table(C.TASK_BINARY)
    df = df[~df["subject"].isin(excl)].reset_index(drop=True)
    cols = feature_cols(df[all_cols], C.CLASSIFIER_MODALITIES)
    # 2. Train the frozen model (logistic regression) in float, then derive its int8 version.
    pipe = make_model().fit(df[cols], df["y"])
    q = quantize(pipe, df[cols])
    # 3. Effort-gate threshold: 99th percentile of the activity index over seated-calm windows.
    raw = pd.read_csv(C.FEAT_DIR / f"{TAG}.csv")
    ref = raw["label"].isin(C.GATE_REF_LABELS) & ~raw["subject"].isin(excl)
    thr = float(np.percentile(raw.loc[ref, "acc_activity"], C.GATE_ACT_PCT))

    # 4. Self-check: how often the int8 model gives the same class as the float model.
    li, ci = int8_logit(q, df[cols])
    lf = float_logit(pipe, df[cols])
    agree = float(np.mean(ci == (lf > 0)))
    print(f"Excluded from training: {excl or 'none (final model)'}")
    print(f"Trained {C.FROZEN_MODEL} on {len(df)} windows ({int(df['y'].sum())} stress), {len(cols)} features")
    print(f"int8 vs float on the training rows: identical class {agree * 100:.2f} % (self-check, not a result)")
    print(f"Gate threshold = P{C.GATE_ACT_PCT} of acc_activity over labels {C.GATE_REF_LABELS}: {thr:.4f} g/s")

    def f(x):
        """C float literal: always has a '.' or exponent before 'f' (0 -> 0.0f, 3 -> 3.0f)."""
        t = f"{float(x):.9g}"
        if not any(ch in t for ch in ".eE"):
            t += ".0"
        return t + "f"
    # 5. Write the C header the firmware includes (weights, scales, scaler, gate threshold).
    lines = [
        "// model_params.h - GENERATED by python/phase_2_export_model.py. Do not edit by hand.",
        f"// Frozen classifier: {C.FROZEN_MODEL}, window {TAG}, normalisation={C.FROZEN_NORM}, int{C.Q_BITS}.",
        f"// Training subjects: all except {excl if excl else 'none'} ({'DEMO model' if excl else 'FINAL model'}).",
        f'#define MODEL_EXCLUDED "{",".join(excl)}"',
        "// Device chain: feature - calibration mean -> NaN->median -> (x-mean)/scale -> clip/round to int8",
        "//               -> acc = sum(qx*QW) + QB (int32) -> class = acc > 0 ; logit = acc * S_X * S_W",
        "#pragma once",
        "#include <stdint.h>",
        "",
        f"#define N_FEAT {len(cols)}",
        "// Feature order (must match the firmware feature extractor):",
        *[f"//   [{i:2d}] {c}" for i, c in enumerate(cols)],
        "",
        arr("FEAT_MEDIAN", "float", q["median"], f),
        arr("FEAT_MEAN", "float", q["mean"], f),
        arr("FEAT_SCALE", "float", q["scale"], f),
        arr("QW", "int8_t", q["qw"], lambda x: str(int(x))),
        "// index of each classifier feature in the device feature vector (config.DEVICE_FEATURES)",
        arr("FEAT_DEV_INDEX", "uint8_t", [C.DEVICE_FEATURES.index(c) for c in cols], lambda x: str(int(x))),
        f"static const int32_t QB = {q['qb']};",
        f"static const float S_X = {f(q['s_x'])};   // input scale (clip {q['clip']:.6g} / 127)",
        f"static const float S_W = {f(q['s_w'])};   // weight scale",
        f"static const float GATE_ACT_THR_GPS = {f(thr)};   // effort gate (F6)",
        "",
    ]
    C.EXPORT_HEADER.parent.mkdir(parents=True, exist_ok=True)
    C.EXPORT_HEADER.write_text("\n".join(lines), encoding="utf-8")

    # 6. Same parameters as JSON, for the documents and for the replay scripts.
    export = {"excluded_subjects": excl, "model": C.FROZEN_MODEL, "window": TAG, "normalised": C.FROZEN_NORM, "features": cols,
              "n_train_windows": int(len(df)), "n_train_stress": int(df["y"].sum()),
              "median": q["median"].tolist(), "mean": q["mean"].tolist(), "scale": q["scale"].tolist(),
              "qw": q["qw"].astype(int).tolist(), "qb": q["qb"], "s_x": q["s_x"], "s_w": q["s_w"],
              "clip_z": q["clip"], "float_coef": pipe[-1].coef_.ravel().tolist(),
              "float_intercept": float(pipe[-1].intercept_[0]), "gate_threshold_gps": thr,
              "int8_float_agreement_train": agree}
    with open(C.LOG_DIR / "SSHRC_L2_model_export.json", "w") as fh:
        json.dump(export, fh, indent=1)

    # 7. Golden test vectors: 50 random training windows with the exact int32 result the
    #    ESP32 must reproduce (checked by phase_3_golden_test.py).
    rng = np.random.default_rng(C.SEED)
    idx = np.sort(rng.choice(len(df), C.N_GOLDEN, replace=False))
    g = df.iloc[idx][["subject", "t_start", "label", *cols]].copy()
    X = g[cols].to_numpy(dtype=float)
    acc_i = np.round(li[idx] / (q["s_x"] * q["s_w"])).astype(np.int64)
    g["expected_acc_int32"] = acc_i
    g["expected_class"] = ci[idx]
    g["expected_logit"] = li[idx]
    g.to_csv(C.LOG_DIR / "SSHRC_L2_golden_classifier.csv", index=False)
    print(f"Wrote {C.EXPORT_HEADER.relative_to(C.ROOT)}, logs/SSHRC_L2_model_export.json, "
          f"logs/SSHRC_L2_golden_classifier.csv ({C.N_GOLDEN} windows)")
    print("QW = " + ", ".join(str(int(x)) for x in q["qw"]) + f" | QB = {q['qb']}")


if __name__ == "__main__":
    with RunLog("phase_2_export_model"):
        main()
